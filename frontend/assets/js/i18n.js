(function () {
    'use strict';

    function getTranslation(language, key) {
        const table = CM_TRANSLATIONS[language] || CM_TRANSLATIONS.English;
        return table[key] || CM_TRANSLATIONS.English[key] || null;
    }

    function applyTranslations(language) {
        const lang = CM_TRANSLATIONS[language] ? language : 'English';

        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            const value = getTranslation(lang, el.getAttribute('data-i18n'));
            if (value !== null) el.textContent = value;
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            const value = getTranslation(lang, el.getAttribute('data-i18n-placeholder'));
            if (value !== null) el.setAttribute('placeholder', value);
        });

        document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            const value = getTranslation(lang, el.getAttribute('data-i18n-title'));
            if (value !== null) el.setAttribute('title', value);
        });

        document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
            const value = getTranslation(lang, el.getAttribute('data-i18n-aria-label'));
            if (value !== null) el.setAttribute('aria-label', value);
        });

        document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
            const value = getTranslation(lang, el.getAttribute('data-i18n-alt'));
            if (value !== null) el.setAttribute('alt', value);
        });
    }

    // Expose globally so header.php's language dropdown (and anything else)
    // can call this instead of maintaining its own separate translation map.
    window.applyTranslations = applyTranslations;

    window.addEventListener('skakmatLanguageChanged', function (event) {
        applyTranslations(event.detail && event.detail.language);
    });

    function init() {
        applyTranslations(localStorage.getItem('skakmat_language') || 'English');
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
})();
